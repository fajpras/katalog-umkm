-- Migrasi US-38: Tabel Ulasan dan Rating Produk
CREATE TABLE IF NOT EXISTS ulasan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  produk_id BIGINT REFERENCES produk(id) ON DELETE CASCADE,
  nama TEXT NOT NULL,
  rating SMALLINT NOT NULL CHECK (rating >= 1 AND rating <= 5),
  komentar TEXT NOT NULL,
  tampil BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Aktifkan RLS
ALTER TABLE ulasan ENABLE ROW LEVEL SECURITY;

-- Policy 1: Publik hanya dapat membaca ulasan yang berstatus tampil = true
CREATE POLICY "Ulasan publik yang tampil dapat dibaca"
  ON ulasan FOR SELECT
  USING (tampil = true);

-- Policy 2: Publik dapat mengirimkan ulasan baru
CREATE POLICY "Publik dapat mengirim ulasan"
  ON ulasan FOR INSERT
  WITH CHECK (true);

-- Policy 3: Admin login dapat membaca, mengubah (moderasi), dan menghapus semua ulasan
CREATE POLICY "Admin dapat mengelola ulasan"
  ON ulasan FOR ALL
  TO authenticated
  USING (true)
  WITH CHECK (true);
