-- Migrasi US-40: Tabel Log Klik WhatsApp
CREATE TABLE IF NOT EXISTS log_klik_wa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  produk_id BIGINT REFERENCES produk(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Aktifkan Row Level Security (RLS)
ALTER TABLE log_klik_wa ENABLE ROW LEVEL SECURITY;

-- Policy 1: Publik dapat mencatat log klik WA (INSERT)
CREATE POLICY "Publik dapat mencatat klik wa"
  ON log_klik_wa FOR INSERT
  WITH CHECK (true);

-- Policy 2: Admin yang sudah login dapat melihat log (SELECT)
CREATE POLICY "Admin dapat melihat log klik wa"
  ON log_klik_wa FOR SELECT
  TO authenticated
  USING (true);
