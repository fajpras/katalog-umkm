-- Migrasi US-42: Tabel Banner Promo Beranda
CREATE TABLE IF NOT EXISTS banner (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  judul TEXT NOT NULL,
  gambar_url TEXT NOT NULL,
  tautan TEXT DEFAULT '',
  aktif BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Aktifkan Row Level Security (RLS)
ALTER TABLE banner ENABLE ROW LEVEL SECURITY;

-- Policy 1: Publik hanya dapat membaca banner yang aktif = true
CREATE POLICY "Banner publik aktif dapat dibaca"
  ON banner FOR SELECT
  USING (aktif = true);

-- Policy 2: Admin login dapat mengelola seluruh data banner
CREATE POLICY "Admin dapat mengelola banner"
  ON banner FOR ALL
  TO authenticated
  USING (true)
  WITH CHECK (true);
